/**
 * 금액 부호 색 — **한국 회계·증시 관습: 플러스 빨강, 마이너스 파랑.**
 *
 * 서양 관습(플러스 초록 / 마이너스 빨강)과 정반대라, 섞여 있으면 같은 화면에서
 * 어떤 빨강은 '늘었다'고 어떤 빨강은 '줄었다'로 읽혀 매번 숫자를 다시 봐야 한다.
 * 실제로 충전 추이 그래프만 한국식이고 나머지(월별 잔액·수기 조정·장부)는 서양식이라
 * 뒤섞여 있었다. 부호에 색을 입히는 자리는 전부 이 헬퍼를 거친다.
 *
 * ⚠️ '좋다/나쁘다'를 말하는 색은 여기 해당하지 않는다. 예를 들어 취소율이 오른 건
 *    플러스지만 나쁜 일이라 danger 로 칠해야 맞다 — 그건 부호 색이 아니라 평가 색이다.
 */
export const SIGN_UP   = '#FF676F'  // 플러스 — 이 앱이 원래 쓰던 빨강(일요일·삭제와 동일)
export const SIGN_DOWN = '#3374FF'  // 마이너스 — 이 앱이 원래 쓰던 파랑(토요일·계정유형·차트와 동일)

/** 0 은 플러스로 친다(= '+0원'으로 표기되므로 색도 플러스 쪽) */
export function signColor(v: number): string {
  return v >= 0 ? SIGN_UP : SIGN_DOWN
}
