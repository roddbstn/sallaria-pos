// 전화번호 포맷 — 한국 번호 체계 전부를 받아낸다.
//
// 왜 유연해야 하나: 매장 연락처로 **안심번호(0507·050x)** 를 쓰는 곳이 많다.
// 안심번호는 `0507-1484-4222` 처럼 4-4-4 라서, 휴대폰 3-4-4 만 가정한 포매터에 넣으면
// `050-7148-4422` 같은 엉뚱한 번호가 된다. (침산점 연락처가 실제로 0507 번호다)
//
// 규칙은 "국번 길이를 먼저 정하고 나머지를 뒤에서 4자리로 끊는다" 하나다.
// 숫자만 남긴 뒤 접두사로 국번 길이를 판단한다.

/** 지역번호 — 02 는 2자리, 나머지는 3자리 */
const AREA_3 = [
  '031', '032', '033', '041', '042', '043', '044',
  '051', '052', '053', '054', '055', '061', '062', '063', '064',
]

/**
 * 앞자리(국번)가 몇 자리인지.
 *
 *  02        서울            → 2
 *  031~064   지역            → 3
 *  010·011…  휴대폰          → 3
 *  0503·0505·0507…  안심번호 → 4   ← 이것 때문에 이 함수가 있다
 *  070       인터넷전화      → 3
 *  15xx·16xx·18xx  대표번호  → 4 (뒤가 4자리뿐이라 2덩이)
 */
function prefixLength(d: string): number {
  if (d.startsWith('02')) return 2
  if (/^050\d/.test(d)) return 4              // 0503·0505·0506·0507 …
  if (/^1[5678]\d\d/.test(d)) return 4        // 1588·1600·1666·1877 …
  // 12자리는 4-4-4 로 떨어진다. 안심번호(050x) 말고도 12자리 특수번호가 있어서
  // 접두사 목록에 없더라도 길이로 판단한다 — 전엔 국번을 3으로 보고
  // `070-12345-6789` 처럼 가운데가 5자리인 이상한 모양이 나왔다.
  if (d.length >= 12) return 4
  if (AREA_3.some(a => d.startsWith(a))) return 3
  if (d.startsWith('0')) return 3             // 010·011·070 …
  return 3
}

/**
 * 가운데 덩어리가 **항상 4자리**인 번호인가.
 *
 * 휴대폰(01x, 총 11자리)과 안심번호(050x, 총 12자리)는 길이가 고정이라
 * 가운데를 4로 못박을 수 있다. 지역번호는 7자리/8자리가 섞여 있어(031-123-4567 /
 * 031-1234-5678) 다 치기 전엔 가운데 길이를 알 수 없다.
 */
function hasFixedMid4(d: string): boolean {
  // 02 는 국번이 2자리라 길이로 밀어붙이면 뒤가 5자리가 된다 — 늘 뒤에서 끊는다.
  if (d.startsWith('02')) return false
  // 11자리는 3-4-4, 12자리는 4-4-4 — 둘 다 가운데가 4다.
  // (국번 길이는 prefixLength 가 정하고, 여기는 "가운데를 4로 볼지"만 정한다)
  return /^01\d/.test(d) || /^050\d/.test(d) || d.length >= 11
}

/**
 * 입력 중에도 자연스럽게 하이픈을 끼운다.
 *
 *   01048713893  → 010-4871-3893   (3-4-4)
 *   050714844222 → 0507-1484-4222  (4-4-4)  ← 안심번호
 *   0212345678   → 02-1234-5678    (2-4-4)
 *   0311234567   → 031-123-4567    (3-3-4)
 *   15881234     → 1588-1234       (4-4)
 *
 *   11자리 → 3-4-4,  12자리 → 4-4-4 (길이만으로 떨어진다)
 *
 * 끊는 방향이 두 가지인 이유:
 *   · 길이가 고정인 번호(휴대폰·안심번호)는 **앞에서** 4자리씩 끊는다.
 *     뒤에서 끊으면 치는 도중에 `010-487-1389` 처럼 보였다가 마지막 글자에서
 *     `010-4871-3893` 로 튄다 — 입력하면서 숫자가 춤춘다.
 *   · 길이가 들쑥날쑥한 지역번호는 **뒤에서** 4자리를 떼야 7자리든 8자리든 맞는다.
 */
export function formatPhone(raw: string): string {
  const d = (raw ?? '').replace(/[^0-9]/g, '').slice(0, 12)
  if (!d) return ''

  const p = prefixLength(d)
  if (d.length <= p) return d

  const head = d.slice(0, p)
  const rest = d.slice(p)

  // 대표번호(15xx 등)는 뒤가 4자리뿐이라 두 덩이로 끝난다
  if (rest.length <= 4) return `${head}-${rest}`

  if (hasFixedMid4(d)) {
    return `${head}-${rest.slice(0, 4)}-${rest.slice(4)}`
  }

  const tail = rest.slice(-4)
  const mid  = rest.slice(0, -4)
  return `${head}-${mid}-${tail}`
}

/** 저장용 — 숫자만 */
export function phoneDigits(raw: string): string {
  return (raw ?? '').replace(/[^0-9]/g, '')
}

/**
 * 쓸 수 있는 번호인가.
 *
 * 길이만 본다. 번호 체계를 엄격히 검사하면 새 번호대가 생길 때마다 막히고,
 * 매장이 "왜 내 번호를 못 넣냐"고 묻게 된다. 8자리(1588-1234)부터 12자리까지 받는다.
 */
export function isValidPhone(raw: string): boolean {
  const d = phoneDigits(raw)
  return d.length >= 8 && d.length <= 12
}
