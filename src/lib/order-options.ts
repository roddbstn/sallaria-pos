// 주문 옵션 중 **화면에 적을 필요가 없는 것**을 걸러낸다.
//
// ── 왜 이런 게 있나 ────────────────────────────────────────────────────────
// 메뉴 데이터에 `가격(필수) - ○○` 이라는 옵션그룹이 있다. 원래는 사이즈·종류를
// 고르는 자리다 — 'HOT 500ml' · 'ICE 1L' · '100g' · '200g' 처럼.
// 그런데 **기본 선택지만은 이름 대신 금액이 적혀 있다**: '13,000원', '8,300원'.
//
// 그래서 주문 팝업의 세트메뉴가 이렇게 보였다:
//     포케+음료선택1 세트 | 1개
//     └ 13,000원        ← 단가 (이건 맞다)
//     └ 13,000원        ← 옵션 '13,000원'
//     └ 저칼로리 스리라차
//     └ 스팀 닭가슴살 포케
//     └ 13,000원        ← 가격 그룹이 둘 붙은 메뉴라 또 나온다
//     └ 현미밥
//     └ ICE 아메리카노
// 주방이 읽어야 하는 건 아래 네 줄인데 금액 세 줄이 먼저 눈에 들어온다.
//
// ── 왜 '옵션 이름'으로 거르나 ──────────────────────────────────────────────
// 그룹 이름(`가격(필수) - …`)으로 거르는 방법도 있지만, 주문 시점에 스냅샷으로
// 남는 건 **옵션 이름과 추가금뿐**이다(order_item_options). 그룹 이름은 지금
// 메뉴 설정을 따라가므로, 점주가 나중에 그룹 이름을 바꾸면 **지난 주문의 표시가
// 같이 바뀐다.** 지난 주문은 그때 그대로 보여야 한다.
//
// ── 안전한가 ──────────────────────────────────────────────────────────────
// 2026-11-02 기준 order_item_options 전체에서 이름이 금액뿐인 행은 637개,
// 그 **전부가 추가금 0원**이다. 추가금이 붙은 금액 이름은 한 건도 없다.
// 그래서 추가금이 0인 것만 거른다 — 0이 아니면 돈이 붙은 실제 선택이므로
// 이름이 뭐든 남긴다.

/** '13,000원' · '8,300 원' 처럼 **값만 적힌** 옵션인가 */
export function isPriceOnlyOption(name: string, extraPrice: number): boolean {
  if (extraPrice !== 0) return false
  return /^[0-9][0-9,]*\s*원$/.test(name.trim())
}
